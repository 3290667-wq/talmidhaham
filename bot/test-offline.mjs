import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
process.env.TALMID_DATA_DIR = mkdtempSync(join(tmpdir(), 'talmid-test-'));
const { handleMessage } = await import('./src/conversation.js');

const A = '972583290667@c.us';
const B = '972500000002@c.us';

let out = [];
let lastButtons = null;
const send = (p) => {
  if (typeof p === 'string') { out.push(p); lastButtons = null; }
  else { out.push(p.text); lastButtons = p.buttons || []; }
};

async function say(user, name, text) {
  out = []; lastButtons = null;
  await handleMessage(user, name, text, send);
  return out.join('\n---\n');
}

const btnIds = () => (lastButtons || []).map((b) => b.id).join(',');

let pass = 0, fail = 0;
function check(label, actual, expect) {
  const ok = typeof expect === 'function' ? expect(actual) : String(actual).includes(expect);
  console.log(`${ok ? '✓' : '✗'} ${label}`);
  if (!ok) { console.log(`   got: ${JSON.stringify(String(actual).slice(0, 160))}`); fail++; } else pass++;
}

// --- שסתום קבוצתי: פטפוט לא מפעיל את הבוט ---
