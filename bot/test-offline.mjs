// --- הגדרות ---
check('א\' - "הגדרות"', await say(A, 'אמיחי', 'הגדרות'), 'שעת המשימה היומית: 7:00');
check('א\' - "שנה שעה 6"', await say(A, 'אמיחי', 'שנה שעה 6'), 'ב-6:00');
check('א\' - שעה לא חוקית נדחית', await say(A, 'אמיחי', 'שנה שעה 30'), 'בין 4 ל-23');
check('א\' - "שנה שבת" מחליף מצב', await say(A, 'אמיחי', 'שנה שבת'), 'לימוד רגיל גם בשבת');
