check('שעה', await say(A, 'אמיחי', '7'), 'לדלג על שבת');
check('שבת', await say(A, 'אמיחי', 'כן'), 'הנה התכנית שלך');
const confirmed = await say(A, 'אמיחי', 'אשר');
check('אישור מפעיל את התכנית', confirmed, 'התכנית הופעלה');
