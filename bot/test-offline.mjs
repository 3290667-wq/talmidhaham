check('גמרא - "דף" בלי מספר', await (async () => { const E='972500000005@c.us'; await say(E,'יעקב','הרשמה'); await say(E,'יעקב','1'); await say(E,'יעקב','ברכות'); return say(E,'יעקב','דף'); })(), 'על מה לבחון');
check('גמרא - קצב גדול מהמסכת נדחה', await (async () => { const F='972500000006@c.us'; await say(F,'שמעון','הרשמה'); await say(F,'שמעון','1'); await say(F,'שמעון','מכות'); return say(F,'שמעון','500 דפים'); })(), 'יותר מכל המסכת');
